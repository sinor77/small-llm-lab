"""
ArithmeticVerifier — programmatic exact-answer verifier for arithmetic problems.

Design:
- No LLM is used as a judge.
- The verifier parses the model's generated text to extract the answer.
- It then compares the extracted answer against the ground-truth numeric value.
- Numerical tolerance is used for floating-point comparisons.
- The verifier handles common formatting variations in model output.

Return format:
    {
        "correct":   bool,
        "predicted": str | None,   # raw extracted string
        "expected":  str,          # ground-truth answer string
        "pred_num":  float | None, # parsed numeric value
        "exp_num":   float,        # expected numeric value
        "reason":    str           # explanation of the decision
    }
"""

import re
import math
from typing import Optional


# ── Numeric tolerance for floating-point comparisons ─────────────────────────

FLOAT_TOL_ABS = 1e-4    # absolute tolerance
FLOAT_TOL_REL = 1e-4    # relative tolerance


# ── Answer extraction ─────────────────────────────────────────────────────────

def _extract_answer(generated_text: str) -> Optional[str]:
    """
    Extract the model's answer from generated text.

    Handles formats:
        "Answer: 42"
        "Answer: -3"
        "Answer: 1.5"
        "Answer: equal"          ← non-numeric (comparison)
        "Answer: 5 + 3"          ← expression answer
        "answer: 42"
        "The answer is 42."
        "= 42"   (fallback)

    Returns the extracted answer string, or None if no answer found.
    """
    text = generated_text.strip()

    # Strategy 1: explicit "Answer:" line — capture everything after the colon
    # on the same line (strip trailing punctuation/whitespace).
    match = re.search(
        r"Answer\s*:\s*(.+?)(?:\n|$)",
        text,
        re.IGNORECASE,
    )
    if match:
        raw = match.group(1).strip().rstrip(".")
        if raw:
            return raw

    # Strategy 2: "the answer is X"
    match = re.search(
        r"(?:the\s+)?answer\s+is\s+(.+?)(?:\.|,|\n|$)",
        text,
        re.IGNORECASE,
    )
    if match:
        raw = match.group(1).strip()
        if raw:
            return raw

    # Strategy 3: last number on last non-empty line (last resort for numeric answers)
    lines = [l.strip() for l in text.split("\n") if l.strip()]
    if lines:
        nums = re.findall(r"([+-]?\d+(?:[.,]\d+)?)", lines[-1])
        if nums:
            return nums[-1]

    return None


def _parse_number(s: str) -> Optional[float]:
    """
    Parse a string to a float.
    Handles: integers, decimals, fractions (e.g. "3/4"), commas as thousands separators.
    """
    if s is None:
        return None

    s = s.strip().replace(",", "")

    # Fraction
    if "/" in s:
        parts = s.split("/")
        if len(parts) == 2:
            try:
                return float(parts[0]) / float(parts[1])
            except (ValueError, ZeroDivisionError):
                return None

    try:
        return float(s)
    except ValueError:
        return None


def _nums_equal(a: float, b: float) -> bool:
    """Check if two floats are close enough to be considered equal."""
    return math.isclose(a, b, rel_tol=FLOAT_TOL_REL, abs_tol=FLOAT_TOL_ABS)


# ── Public API ────────────────────────────────────────────────────────────────

def verify(
    generated_text: str,
    expected_answer: str,
    expected_num: float,
) -> dict:
    """
    Verify a model-generated response against the expected answer.

    Args:
        generated_text:  full text generated by the model
        expected_answer: canonical answer string (from Example.answer)
        expected_num:    canonical numeric value (from Example.answer_num)

    Returns:
        dict with keys: correct, predicted, expected, pred_num, exp_num, reason
    """
    pred_str = _extract_answer(generated_text)
    pred_num = _parse_number(pred_str)

    result = {
        "correct":   False,
        "predicted": pred_str,
        "expected":  expected_answer,
        "pred_num":  pred_num,
        "exp_num":   expected_num,
        "reason":    "",
    }

    if pred_str is None:
        result["reason"] = "no answer found in generated text"
        return result

    if pred_num is None:
        # Try string comparison for non-numeric answers (e.g., comparison problems)
        pred_clean = pred_str.strip().lower()
        exp_clean  = expected_answer.strip().lower()
        if pred_clean == exp_clean:
            result["correct"] = True
            result["reason"]  = "exact string match"
        else:
            result["reason"] = f"could not parse '{pred_str}' as a number; string mismatch"
        return result

    # Numeric comparison
    if _nums_equal(pred_num, expected_num):
        result["correct"] = True
        result["reason"]  = f"numeric match ({pred_num} ≈ {expected_num})"
    else:
        result["reason"] = f"numeric mismatch: predicted {pred_num}, expected {expected_num}"

    return result


def verify_batch(
    generated_texts: list,
    expected_answers: list,
    expected_nums: list,
) -> list:
    """Verify a batch of generated texts against expected answers."""
    assert len(generated_texts) == len(expected_answers) == len(expected_nums)
    return [
        verify(g, a, n)
        for g, a, n in zip(generated_texts, expected_answers, expected_nums)
    ]
